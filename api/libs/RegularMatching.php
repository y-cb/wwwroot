<?php
namespace lib;

class RegularMatching {
    /**
     * ip正则匹配
     * @param $string
     * @return bool
     */
    function checkIP($string){
        if(preg_match('/^((?:(?:25[0-5]|2[0-4]\d|((1\d{2})|([1-9]?\d)))\.){3}(?:25[0-5]|2[0-4]\d|((1\d{2})|([1-9]?\d))))$/', $string))
        {
            $ip = explode('.',$string);
            if ($ip[0] == '0' && $string != '0.0.0.0') {
                return false;
            } else {
                foreach ($ip as $key) {
                    if((int)$key > 255) {
                        return false;
                    }
                }
            }
            return true;
        } else {
            return false;
        }
    }

    function checkIPv6($string){
        if(preg_match('/^([\da-fA-F]{1,4}:){6}(\d{1,2}|1\d\d|2[0-4]\d|25[0-5])(\.(\d{1,2}|1\d\d|2[0-4]\d|25[0-5])){3}$|^([\da-fA-F]{1,4}:){1,5}:(\d{1,2}|1\d\d|2[0-4]\d|25[0-5])(\.(\d{1,2}|1\d\d|2[0-4]\d|25[0-5])){3}$|^::(([\da-fA-F]{1,4}:){0,5})(\d{1,2}|1\d\d|2[0-4]\d|25[0-5])(\.(\d{1,2}|1\d\d|2[0-4]\d|25[0-5])){3}$|^([\da-fA-F]{1,4}::([\da-fA-F]{1,4}:){0,4})(\d{1,2}|1\d\d|2[0-4]\d|25[0-5])(\.(\d{1,2}|1\d\d|2[0-4]\d|25[0-5])){3}$|^(([\da-fA-F]{1,4}:){2}:([\da-fA-F]{1,4}:){0,3})(\d{1,2}|1\d\d|2[0-4]\d|25[0-5])(\.(\d{1,2}|1\d\d|2[0-4]\d|25[0-5])){3}$|^(([\da-fA-F]{1,4}:){3}:([\da-fA-F]{1,4}:){0,2})(\d{1,2}|1\d\d|2[0-4]\d|25[0-5])(\.(\d{1,2}|1\d\d|2[0-4]\d|25[0-5])){3}$|^(([\da-fA-F]{1,4}:){4}:([\da-fA-F]{1,4}:){0,1})(\d{1,2}|1\d\d|2[0-4]\d|25[0-5])(\.(\d{1,2}|1\d\d|2[0-4]\d|25[0-5])){3}$|^:((:[\da-fA-F]{1,4}){1,7}|:)$|^([\da-fA-F]{1,4}:){1}((:[\da-fA-F]{1,4}){1,6}|:)$|^([\da-fA-F]{1,4}:){2}((:[\da-fA-F]{1,4}){1,5}|:)$|^([\da-fA-F]{1,4}:){3}((:[\da-fA-F]{1,4}){1,4}|:)$|^([\da-fA-F]{1,4}:){4}((:[\da-fA-F]{1,4}){1,3}|:)$|^([\da-fA-F]{1,4}:){5}((:[\da-fA-F]{1,4}){1,2}|:)$|^([\da-fA-F]{1,4}:){6}((:[\da-fA-F]{1,4})|:)$|^([\da-fA-F]{1,4}:){7}(([\da-fA-F]{1,4})|:)$/',$string)){
            return true;
        }else{
            return false;
        }

    }
}